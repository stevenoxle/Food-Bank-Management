-- INFO2413 - Online Food Bank Management System (Option 1)
-- MySQL 8.0.16+ schema for the Implementation stage.
-- Import into an EMPTY local MySQL server through phpMyAdmin or MySQL Workbench.
-- This file creates tables, foreign keys, indexes, report views, and reference data.
-- It does NOT create application users or usable login passwords.
--
-- IMPORTANT SECURITY NOTE:
-- accounts.role and role_permissions are for the JAVA WEB APPLICATION.
-- They do not automatically restrict SQL queries. The backend MUST check a
-- logged-in user's role AND ownership (e.g. donations.donor_id = session ID).
-- Do not give donors direct MySQL credentials or unrestricted table access.
-- Coordinators are the "Managers/Admin" referred to by the team.

CREATE DATABASE IF NOT EXISTS food_bank_management
    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE food_bank_management;

-- 1. Login identities and application-wide roles.
-- Passwords must be generated by Java using BCrypt/Argon2, never plaintext.
-- New recipients register with PENDING status; coordinator approves to ACTIVE.
CREATE TABLE IF NOT EXISTS accounts (
    account_id           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    role                 ENUM('DONOR','RECIPIENT','VOLUNTEER','COORDINATOR') NOT NULL,
    account_status       ENUM('PENDING','ACTIVE','REJECTED','DISABLED') NOT NULL DEFAULT 'PENDING',
    full_name            VARCHAR(150) NOT NULL,
    email                VARCHAR(255) NOT NULL,
    phone                VARCHAR(30) NOT NULL,
    password_hash        VARCHAR(255) NOT NULL,
    created_by_account_id BIGINT UNSIGNED NULL,
    created_at           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at           DATETIME NULL,
    PRIMARY KEY (account_id),
    UNIQUE KEY uq_accounts_email (email),
    KEY idx_accounts_name (full_name),
    KEY idx_accounts_role_status (role, account_status),
    CONSTRAINT fk_accounts_created_by FOREIGN KEY (created_by_account_id)
        REFERENCES accounts(account_id) ON DELETE RESTRICT
) ENGINE=InnoDB;

