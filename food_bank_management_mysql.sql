-- 10. Read-only reporting views for coordinators (filter by report year/month).
-- Donation totals count food PHYSICALLY RECEIVED, not unreceived pledges.
CREATE OR REPLACE VIEW vw_monthly_donation_by_category AS
SELECT YEAR(d.received_at) AS report_year,
       MONTH(d.received_at) AS report_month,
       c.category_id, c.category_name,
       di.unit,
       SUM(il.quantity_received) AS total_quantity_received
FROM donations d
JOIN donation_items di ON di.donation_id = d.donation_id
JOIN inventory_lots il ON il.donation_item_id = di.donation_item_id
JOIN inventory_categories c ON c.category_id = di.category_id
WHERE d.donation_status = 'RECEIVED' AND d.received_at IS NOT NULL
GROUP BY YEAR(d.received_at), MONTH(d.received_at),
         c.category_id, c.category_name, di.unit;

CREATE OR REPLACE VIEW vw_monthly_hampers_distributed AS
SELECT YEAR(distributed_at) AS report_year,
       MONTH(distributed_at) AS report_month,
       COUNT(*) AS total_hampers_distributed
FROM distribution_records
GROUP BY YEAR(distributed_at), MONTH(distributed_at);

CREATE OR REPLACE VIEW vw_monthly_pickup_issues_by_recipient AS
SELECT YEAR(hr.scheduled_pickup_at) AS report_year,
       MONTH(hr.scheduled_pickup_at) AS report_month,
       hr.recipient_id, a.full_name AS recipient_name,
       COUNT(DISTINCT CASE WHEN e.new_status = 'MISSED' THEN hr.request_id END) AS missed_pickups,
       COUNT(DISTINCT CASE WHEN e.new_status = 'DELAYED' THEN hr.request_id END) AS delayed_pickups,
       COUNT(DISTINCT CASE WHEN e.new_status IN ('MISSED','DELAYED')
                           THEN hr.request_id END) AS total_affected_pickups
FROM hamper_requests hr
JOIN accounts a ON a.account_id = hr.recipient_id
LEFT JOIN pickup_status_events e ON e.request_id = hr.request_id
WHERE hr.scheduled_pickup_at IS NOT NULL
GROUP BY YEAR(hr.scheduled_pickup_at), MONTH(hr.scheduled_pickup_at),
         hr.recipient_id, a.full_name
HAVING total_affected_pickups > 0;

CREATE OR REPLACE VIEW vw_monthly_inventory_waste AS
SELECT YEAR(w.wasted_at) AS report_year,
       MONTH(w.wasted_at) AS report_month,
       c.category_id, c.category_name,
       di.unit,
       SUM(w.quantity) AS total_quantity_wasted
FROM inventory_waste w
JOIN inventory_lots il ON il.inventory_lot_id = w.inventory_lot_id
JOIN donation_items di ON di.donation_item_id = il.donation_item_id
JOIN inventory_categories c ON c.category_id = di.category_id
GROUP BY YEAR(w.wasted_at), MONTH(w.wasted_at),
         c.category_id, c.category_name, di.unit;

CREATE OR REPLACE VIEW vw_current_inventory AS
SELECT il.inventory_lot_id, di.item_name,
       di.category_id, c.category_name,
       di.expiry_date, di.unit,
       il.quantity_received, il.quantity_available, il.quantity_wasted,
       il.lot_status, il.storage_location, il.stocked_at,
       d.donation_id, d.donor_id
FROM inventory_lots il
JOIN donation_items di ON di.donation_item_id = il.donation_item_id
JOIN inventory_categories c ON c.category_id = di.category_id
JOIN donations d ON d.donation_id = di.donation_id;

