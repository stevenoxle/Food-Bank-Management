-- 8. Store risk-detection algorithm results, so the team can demonstrate them.
-- Java can calculate avg_daily_distribution_rate from recent distribution_items.
-- expected_demand_before_expiry = rate * max(days_until_expiry, 0).
-- predicted_waste = max(quantity_available - expected_demand_before_expiry, 0).
CREATE TABLE IF NOT EXISTS inventory_risk_assessments (
    risk_assessment_id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    inventory_lot_id          BIGINT UNSIGNED NOT NULL,
    assessed_at               DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    days_until_expiry         INT NULL,
    avg_daily_distribution_rate DECIMAL(12,4) NOT NULL DEFAULT 0,
    expected_demand_before_expiry DECIMAL(12,2) NOT NULL DEFAULT 0,
    predicted_waste_quantity  DECIMAL(12,2) NOT NULL DEFAULT 0,
    risk_level                ENUM('LOW','MEDIUM','HIGH','EXPIRED') NOT NULL,
    explanation               VARCHAR(500) NOT NULL,
    PRIMARY KEY (risk_assessment_id),
    KEY idx_risk_lot_date (inventory_lot_id, assessed_at),
    KEY idx_risk_level_date (risk_level, assessed_at),
    CONSTRAINT chk_risk_nonnegative CHECK (
        avg_daily_distribution_rate >= 0 AND
        expected_demand_before_expiry >= 0 AND predicted_waste_quantity >= 0
    ),
    CONSTRAINT fk_risk_lot FOREIGN KEY (inventory_lot_id)
        REFERENCES inventory_lots(inventory_lot_id) ON DELETE RESTRICT
) ENGINE=InnoDB;

-- 9. The Java application creates alerts and sends actual emails separately.
-- MySQL alone does not send emails, and storing an alert is not delivery.
CREATE TABLE IF NOT EXISTS system_alerts (
    alert_id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    alert_type       ENUM('PICKUP_MISSED','PICKUP_DELAYED','INVENTORY_AT_RISK') NOT NULL,
    request_id       BIGINT UNSIGNED NULL,
    inventory_lot_id BIGINT UNSIGNED NULL,
    email_subject    VARCHAR(255) NOT NULL,
    email_body       TEXT NOT NULL,
    created_at       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (alert_id),
    KEY idx_alert_type_date (alert_type, created_at),
    CONSTRAINT fk_alert_request FOREIGN KEY (request_id)
        REFERENCES hamper_requests(request_id) ON DELETE RESTRICT,
    CONSTRAINT fk_alert_lot FOREIGN KEY (inventory_lot_id)
        REFERENCES inventory_lots(inventory_lot_id) ON DELETE RESTRICT,
    CONSTRAINT chk_alert_target CHECK (
        (alert_type IN ('PICKUP_MISSED','PICKUP_DELAYED')
            AND request_id IS NOT NULL AND inventory_lot_id IS NULL)
        OR
        (alert_type = 'INVENTORY_AT_RISK'
            AND inventory_lot_id IS NOT NULL AND request_id IS NULL)
    )
