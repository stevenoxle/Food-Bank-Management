-- 5. A donor submits a donation; a volunteer marks it RECEIVED at drop-off.
CREATE TABLE IF NOT EXISTS donations (
    donation_id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    donor_id               BIGINT UNSIGNED NOT NULL,
    donation_status        ENUM('SUBMITTED','RECEIVED','CANCELLED') NOT NULL DEFAULT 'SUBMITTED',
    submitted_at           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    received_at            DATETIME NULL,
    received_by_account_id BIGINT UNSIGNED NULL,
    notes                  TEXT NULL,
    PRIMARY KEY (donation_id),
    KEY idx_donations_donor_date (donor_id, submitted_at),
    KEY idx_donations_received_date (donation_status, received_at),
    CONSTRAINT fk_donations_donor FOREIGN KEY (donor_id)
        REFERENCES accounts(account_id) ON DELETE RESTRICT,
    CONSTRAINT fk_donations_received_by FOREIGN KEY (received_by_account_id)
        REFERENCES accounts(account_id) ON DELETE RESTRICT
) ENGINE=InnoDB;

-- One donation may contain MULTIPLE item types and quantities.
CREATE TABLE IF NOT EXISTS donation_items (
    donation_item_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    donation_id      BIGINT UNSIGNED NOT NULL,
    category_id      SMALLINT UNSIGNED NOT NULL,
    item_name        VARCHAR(150) NOT NULL,
    quantity         DECIMAL(12,2) NOT NULL,
    unit             VARCHAR(30) NOT NULL,
    expiry_date      DATE NULL,
    PRIMARY KEY (donation_item_id),
    KEY idx_donation_items_category (category_id),
    KEY idx_donation_items_expiry (expiry_date),
    CONSTRAINT chk_donation_item_quantity CHECK (quantity > 0),
    CONSTRAINT fk_donation_item_donation FOREIGN KEY (donation_id)
        REFERENCES donations(donation_id) ON DELETE RESTRICT,
    CONSTRAINT fk_donation_item_category FOREIGN KEY (category_id)
        REFERENCES inventory_categories(category_id) ON DELETE RESTRICT
) ENGINE=InnoDB;

-- A received item creates one traceable inventory lot.
-- Example: 10 cans donated, 6 in stock, 2 distributed, 2 wasted.
-- So: received(10) - available(6) - wasted(2) = distributed(2).
CREATE TABLE IF NOT EXISTS inventory_lots (
    inventory_lot_id   BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    donation_item_id   BIGINT UNSIGNED NOT NULL,
    quantity_received  DECIMAL(12,2) NOT NULL,
    quantity_available DECIMAL(12,2) NOT NULL,
    quantity_wasted    DECIMAL(12,2) NOT NULL DEFAULT 0,
    storage_location   VARCHAR(120) NULL,
    lot_status         ENUM('AVAILABLE','DEPLETED','EXPIRED','DISCARDED') NOT NULL DEFAULT 'AVAILABLE',
    stocked_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (inventory_lot_id),
    UNIQUE KEY uq_inventory_donation_item (donation_item_id),
    KEY idx_inventory_status (lot_status),
    KEY idx_inventory_available (quantity_available),
    CONSTRAINT chk_inventory_received CHECK (quantity_received > 0),
    CONSTRAINT chk_inventory_quantities CHECK (
        quantity_available >= 0 AND quantity_wasted >= 0 AND
        quantity_available + quantity_wasted <= quantity_received
    ),
    CONSTRAINT fk_inventory_donation_item FOREIGN KEY (donation_item_id)
        REFERENCES donation_items(donation_item_id) ON DELETE RESTRICT
) ENGINE=InnoDB;

-- Waste is logged separately, allowing category/month reports and auditing.
-- Java must deduct the same amount from inventory_lots.quantity_available
-- and add it to quantity_wasted IN ONE DATABASE TRANSACTION.
CREATE TABLE IF NOT EXISTS inventory_waste (
    waste_id               BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    inventory_lot_id       BIGINT UNSIGNED NOT NULL,
    quantity               DECIMAL(12,2) NOT NULL,
    waste_reason           ENUM('EXPIRED','SPOILED','DAMAGED','OTHER') NOT NULL,
    recorded_by_account_id BIGINT UNSIGNED NOT NULL,
    wasted_at              DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes                  TEXT NULL,
    PRIMARY KEY (waste_id),
    KEY idx_waste_date (wasted_at),
    CONSTRAINT chk_waste_quantity CHECK (quantity > 0),
    CONSTRAINT fk_waste_lot FOREIGN KEY (inventory_lot_id)
        REFERENCES inventory_lots(inventory_lot_id) ON DELETE RESTRICT,
    CONSTRAINT fk_waste_recorded_by FOREIGN KEY (recorded_by_account_id)
        REFERENCES accounts(account_id) ON DELETE RESTRICT
) ENGINE=InnoDB;

